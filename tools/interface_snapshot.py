"""Record the public interface of every group stub module (OWNED BY A1).

    .venv/Scripts/python.exe tools/interface_snapshot.py --write tests/interface_snapshot.json

Run by the architect while every group module is still a stub (A1 first; regenerated by A2 on
2026-11-17 after the SPEC revision); groups must never regenerate the file.
tests/test_interfaces.py then checks that the real modules keep every recorded name, parameter
(same name, order and kind; recorded defaults stay optional), Qt signal AND its signature
(QMetaMethod.methodSignature, e.g. "progress(int,int,double)"), property, enum member,
dataclass field and Qt base class. Additions are always allowed.

A module is a stub when its source starts with "# OWNED BY G". Only names DEFINED in the module
are recorded (imports are ignored). Pure AST plus importing the module to resolve base classes
and the signal signatures (``cls.staticMetaObject``; no instance is created).
"""

from __future__ import annotations

import argparse
import ast
import importlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


INTERNAL: frozenset[str] = frozenset({
    # G4-internal building blocks: free to change (the UI only uses RunSession / preflight / preview)
    "autopress.runner.engine.Runner", "autopress.runner.backend.Backend", "autopress.runner.backend.RealBackend",
    "autopress.runner.steps.execute_step", "autopress.runner.steps.StepOutcome", "autopress.runner.steps.StepError",
    "autopress.runner.steps.render_template",
})


def _params(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> list[dict[str, object]]:
    a = fn.args
    out: list[dict[str, object]] = []
    positional = list(a.posonlyargs) + list(a.args)
    n_def = len(a.defaults)
    for i, arg in enumerate(positional):
        kind = "positional_only" if i < len(a.posonlyargs) else "positional_or_keyword"
        out.append({"name": arg.arg, "kind": kind, "default": i >= len(positional) - n_def})
    if a.vararg is not None:
        out.append({"name": a.vararg.arg, "kind": "var_positional", "default": False})
    for arg, d in zip(a.kwonlyargs, a.kw_defaults):
        out.append({"name": arg.arg, "kind": "keyword_only", "default": d is not None})
    if a.kwarg is not None:
        out.append({"name": a.kwarg.arg, "kind": "var_keyword", "default": False})
    return out


def _is_public(name: str) -> bool:
    return not name.startswith("_") or (name.startswith("__") and name.endswith("__") and name != "__stub__")


def _qualname(obj: object) -> str:
    return f"{getattr(obj, '__module__', '')}.{getattr(obj, '__qualname__', getattr(obj, '__name__', ''))}"


def signal_signatures(cls: object, names: list[str] | None = None) -> dict[str, str]:
    """{signal name: QMetaMethod.methodSignature()} of a QObject subclass (class level, no
    instance), restricted to ``names`` when given. Also used by tests/test_interfaces.py."""
    mo = getattr(cls, "staticMetaObject", None)
    if mo is None:
        return {}
    from PyQt6.QtCore import QMetaMethod

    out: dict[str, str] = {}
    for i in range(mo.methodCount()):
        meth = mo.method(i)
        if meth.methodType() != QMetaMethod.MethodType.Signal:
            continue
        sig = bytes(meth.methodSignature()).decode()
        name = sig.split("(", 1)[0]
        if names is None or name in names:
            out[name] = sig
    return out


def snapshot_module(modname: str, path: Path) -> dict[str, object]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    mod = importlib.import_module(modname)
    entry: dict[str, object] = {"functions": {}, "classes": {}, "constants": []}
    for node in tree.body:
        if getattr(node, "name", None) and f"{modname}.{node.name}" in INTERNAL:
            continue
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and _is_public(node.name) and not node.name.startswith("__"):
            entry["functions"][node.name] = _params(node)  # type: ignore[index]
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            cls_obj = getattr(mod, node.name)
            info: dict[str, object] = {"bases": [], "methods": {}, "properties": [], "signals": [],
                                       "enum_members": {}, "fields": []}
            for b in cls_obj.__bases__:
                if b is object or getattr(b, "__module__", "") == "typing":
                    continue
                info["bases"].append(_qualname(b))  # type: ignore[union-attr]
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    if not _is_public(item.name):
                        continue
                    decos = {d.id for d in item.decorator_list if isinstance(d, ast.Name)}
                    if "property" in decos:
                        info["properties"].append(item.name)  # type: ignore[union-attr]
                    else:
                        info["methods"][item.name] = _params(item)  # type: ignore[index]
                elif isinstance(item, ast.Assign) and len(item.targets) == 1 and isinstance(item.targets[0], ast.Name):
                    name = item.targets[0].id
                    if isinstance(item.value, ast.Call) and getattr(item.value.func, "id", "") == "pyqtSignal":
                        info["signals"].append(name)  # type: ignore[union-attr]
                    elif isinstance(item.value, ast.Constant) and not name.startswith("_"):
                        info["enum_members"][name] = item.value.value  # type: ignore[index]
                elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    if not item.target.id.startswith("_"):
                        info["fields"].append(item.target.id)  # type: ignore[union-attr]
            if info["signals"]:
                info["signal_signatures"] = signal_signatures(cls_obj, list(info["signals"]))  # type: ignore[arg-type]
            entry["classes"][node.name] = info  # type: ignore[index]
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                names = [t] if isinstance(t, ast.Name) else (t.elts if isinstance(t, ast.Tuple) else [])
                for n in names:
                    if isinstance(n, ast.Name) and not n.id.startswith("_"):
                        entry["constants"].append(n.id)  # type: ignore[union-attr]
    return entry


def stub_modules() -> list[tuple[str, Path]]:
    out = []
    for p in sorted(list((ROOT / "autopress").rglob("*.py")) + list((ROOT / "tools").glob("*.py")) + [ROOT / "main.py"]):
        if not p.read_text(encoding="utf-8").startswith("# OWNED BY G"):
            continue
        rel = p.relative_to(ROOT).with_suffix("")
        parts = list(rel.parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        out.append((".".join(parts), p))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", required=True, help="output JSON path")
    args = ap.parse_args(argv)
    import os

    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    data = {"note": "Generated from the group stubs by tools/interface_snapshot.py (A1). Do not edit or regenerate.",
            "modules": {name: snapshot_module(name, path) for name, path in stub_modules()}}
    Path(args.write).write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    n = sum(len(m["functions"]) + len(m["classes"]) for m in data["modules"].values())
    print(f"{len(data['modules'])} modules, {n} functions/classes -> {args.write}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
